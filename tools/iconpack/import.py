#!/usr/bin/env python3
"""Imports a Bear Bones icon pack into the app.

Usage: python3 tools/iconpack/import.py <folder or .zip containing bb_<glyph>.png files>

Copies each bb_<glyph>.png listed in glyphs.txt into res/drawable-nodpi and writes res/xml/appfilter.xml
(the standard icon-pack map the app already reads), so the pack shows up as "Bear Bones (built-in)".
"""
import shutil
import sys
import tempfile
import zipfile
from pathlib import Path
from xml.sax.saxutils import quoteattr

root = Path(__file__).resolve().parents[2]
res = root / "app/src/main/res"
src = Path(sys.argv[1]).expanduser()
if src.suffix == ".zip":
    tmp = Path(tempfile.mkdtemp())
    zipfile.ZipFile(src).extractall(tmp)
    src = tmp

pngs = {p.stem.lower(): p for p in src.rglob("*.png")}
out_dir = res / "drawable-nodpi"
out_dir.mkdir(parents=True, exist_ok=True)
items, found, missing = [], [], []
for line in (Path(__file__).parent / "glyphs.txt").read_text().splitlines():
    if not line.strip() or line.startswith("#"):
        continue
    glyph, _, components = [part.strip() for part in line.split("|", 2)]
    name = f"bb_{glyph}"
    if name not in pngs:
        missing.append(name)
        continue
    shutil.copy(pngs[name], out_dir / f"{name}.png")
    found.append(name)
    for c in filter(None, (c.strip() for c in components.split(";"))):
        items.append(f"    <item component={quoteattr('ComponentInfo{' + c + '}')} drawable=\"{name}\" />")

(res / "xml").mkdir(exist_ok=True)
(res / "xml/appfilter.xml").write_text(
    '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/iconpack/import.py -->\n<resources>\n'
    + "\n".join(items) + "\n</resources>\n"
)
print(f"Imported {len(found)} icons, mapped {len(items)} apps.")
if missing:
    print("Missing (those apps keep their own icon):", ", ".join(missing))
